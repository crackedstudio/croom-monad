#!/usr/bin/env python3
"""Generate web/src/deployments.ts from the records in deployments/.

The README's address table and the frontend both come from the same place, for the same reason: a
wrong address in a submission is indistinguishable from a project that does not work.
"""
import json
import pathlib
import sys

CHAIN = "10143"


def main() -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    src = root / "deployments" / CHAIN
    if not src.is_dir():
        print(f"no deployments at {src}", file=sys.stderr)
        return 1

    found = {}
    for path in sorted(src.glob("*.json")):
        record = json.loads(path.read_text())
        found[record["contract"]] = {
            "address": record["address"],
            "block": record["block"],
            "txHash": record["txHash"],
        }

    lines = [
        "// GENERATED by bin/gen-addresses.py from deployments/%s/. Do not edit." % CHAIN,
        "//",
        "// Hand-typing an address is how a working project comes to look broken.",
        "",
        "export const CHAIN_ID = %s;" % CHAIN,
        'export const RPC_URL = "https://testnet-rpc.monad.xyz";',
        'export const EXPLORER = "https://testnet.monadscan.com";',
        "",
        "export const DEPLOYMENTS = {",
    ]
    for name, meta in found.items():
        lines.append(
            '  %s: { address: "%s" as const, block: %d, txHash: "%s" },'
            % (name, meta["address"], meta["block"], meta["txHash"])
        )
    lines += ["} as const;", ""]

    rooms = root / "deployments" / CHAIN / "rooms.txt"
    if rooms.exists():
        ids = [l.strip() for l in rooms.read_text().splitlines() if l.strip()]
        lines += ["export const ROOM_IDS = ["]
        lines += ['  "%s",' % i for i in ids]
        lines += ["] as const;", ""]

    out = root / "web" / "src" / "deployments.ts"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"{out}: {', '.join(found)}" + (f", {len(ids)} rooms" if rooms.exists() else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
